// Only structured numeric vehicle values are eligible; prose and identifiers stay intact.
export function formatVehicleValue(value: string, language: Language): string {
  if (language !== "en") return value;
  const match = value.match(/^(\d+(?:\.\d{3})*(?:,\d{1,2})?)\s*(VNĐ|VND|đ|km|kWh|kW|%)(\s+\((?:NEDC|WLTP)\))?$/);
  if (!match) return value;
  const [, number, unit, standard = ""] = match;
  const [integer, decimal] = number.split(",");
  const formatted = integer.replace(/\./g, "").replace(/\B(?=(\d{3})+(?!\d))/g, ",") + (decimal === undefined ? "" : "." + decimal);
  return formatted + " " + (unit === "VNĐ" || unit === "đ" ? "VND" : unit) + standard;
}

export function translate(text: string, language: Language): string {
  return language === "en" ? ENGLISH[text] || text : text;
}
const LocaleContext = createContext({ language: "vi" as Language, setLanguage: (_language: Language) => {}, getSelectionVersion: (): number => 0 });
export function LocaleProvider({ children, initialLanguage = "vi" }: { children: React.ReactNode; initialLanguage?: Language }) {
  const [language, updateLanguage] = useState<Language>(initialLanguage);
  const selectionVersion = useRef(0);
  const setLanguage = (value: Language) => { selectionVersion.current++; updateLanguage(value); };
  const [restored, setRestored] = useState(false);
  useEffect(() => {
    try { const saved = localStorage.getItem("vf_language"); if (saved === "en" || saved === "vi") updateLanguage(saved); } catch {}
    setRestored(true);
  }, []);
  useEffect(() => {
    if (!restored) return;
    document.documentElement.lang = language;
    try { localStorage.setItem("vf_language", language); } catch {}
  }, [language, restored]);
  return <LocaleContext.Provider value={{language, setLanguage, getSelectionVersion: () => selectionVersion.current}}>{children}</LocaleContext.Provider>;
}
export function useLocale(messageLanguage?: Language) {
  const locale = useContext(LocaleContext);
  const language = messageLanguage || locale.language;
  return {...locale, language, t: (text: string) => translate(text, language)};
}
